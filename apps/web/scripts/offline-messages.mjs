import { readFile } from "node:fs/promises";
import path from "node:path";

/** Catalog namespaces the offline shell renders: its own copy plus the SOAP editor's. */
const pick = (catalog) => ({
  offline: catalog.offline,
  records: { editor: catalog.records.editor },
});

/** Source of offline/messages.generated.ts, built from messages/{en,es}.json. */
export async function renderOfflineMessages(root) {
  const load = async (language) =>
    pick(JSON.parse(await readFile(path.join(root, "messages", `${language}.json`), "utf8")));
  const messages = { en: await load("en"), es: await load("es") };
  return (
    "// Generated by scripts/build-offline.mjs from messages/*.json. Do not edit.\n" +
    `export const OFFLINE_MESSAGES = ${JSON.stringify(messages, null, 2)};\n`
  );
}
